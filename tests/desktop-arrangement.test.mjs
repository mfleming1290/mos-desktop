import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createLayout} from '../runtime/layout.mjs';
import {createArrangement} from '../page/src/desktop-arrangement.mjs';
const arrangement=createArrangement(await createLayout(readFileSync(new URL('../runtime/layout.wasm',import.meta.url))));
const windows=['A','B'].map((id,index)=>({id,bounds:{x:20+index*350,y:40,width:300,height:220},restoredBounds:null,visible:true,presentation:{kind:'NORMAL'}}));
const minimum=()=>({width:160,height:130});
test('host presets preserve floating intent, remap persisted membership and collapse closed tabs',()=>{
  const initial=arrangement.sync(null,windows);
  const tabs=arrangement.preset(initial,windows,'tabs');
  const projected=arrangement.project(tabs,windows,{width:1000,height:600},minimum);
  assert.equal(projected.views.filter(v=>v.active).length,1);
  const tiledWindows=windows.map(w=>({...w,bounds:projected.views.find(v=>v.view===w.id).bounds}));
  const free=arrangement.preset(tabs,tiledWindows,'freeform');
  assert.deepEqual(free.floating,initial.floating);
  const restored=arrangement.restore(JSON.parse(JSON.stringify(tabs)),new Map([['A','newA'],['B','newB']]));
  assert.deepEqual(restored.tiled.root.views,['newA','newB']);
  assert.equal(restored.tiled.root.active,'newB');
  const minimized=arrangement.sync(tabs,windows.map(w=>w.id==='B'?{...w,presentation:{kind:'MINIMIZED'}}:w));
  assert.equal(minimized.tiled.root.active,'A');
  const closed=arrangement.sync(tabs,[windows[0]]);
  assert.equal(closed.floating.length,1);
  assert.equal(arrangement.project(closed,[windows[0]],{width:1000,height:600},minimum).views[0].active,true);
  assert.throws(()=>arrangement.restore({...tabs,version:99},new Map()),/Unsupported/);
  assert.throws(()=>arrangement.restore(tabs,new Map([['A','newA']])),/unavailable/);
  assert.equal(arrangement.project(tabs,windows,{width:0,height:0},minimum).code,'deferred');
  assert.throws(()=>arrangement.project(tabs,windows,{width:50,height:50},minimum));
  assert.deepEqual(tabs.floating,initial.floating);
});
